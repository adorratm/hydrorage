export type AppLocale = 'tr' | 'en';

export const LOCALES: AppLocale[] = ['tr', 'en'];

export function isAppLocale(v: unknown): v is AppLocale {
  return v === 'tr' || v === 'en';
}

export function localeTag(locale: AppLocale): string {
  return locale === 'en' ? 'en-US' : 'tr-TR';
}

export function parseLocale(v: unknown, fallback: AppLocale = 'tr'): AppLocale {
  if (typeof v === 'string') {
    const lower = v.toLowerCase();
    if (lower.startsWith('en')) return 'en';
    if (lower.startsWith('tr')) return 'tr';
  }
  return fallback;
}

